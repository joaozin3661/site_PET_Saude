ALUNOS_JSON = os.path.join(UPLOAD_FOLDER, 'alunos.json')

def load_alunos_db():
    if not os.path.exists(ALUNOS_JSON): 
        return {}
    try:
        with open(ALUNOS_JSON, 'r', encoding='utf-8') as f:
            return json.load(f)
    except json.JSONDecodeError:
        return {}

def save_alunos_db(alunos_dict):
    with open(ALUNOS_JSON, 'w', encoding='utf-8') as f:
        json.dump(alunos_dict, f, ensure_ascii=False, indent=4)

