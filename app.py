@app.route('/noticias/criar', methods=['GET', 'POST'])
def criar_noticia():
    if 'usuario_logado' not in session:
        return redirect(url_for('login'))
    
    if request.method == 'POST':
        titulo = request.form.get('titulo')
        conteudo = request.form.get('conteudo')
        
        # 1. Pega o arquivo de imagem enviado no formulário
        capa = request.files.get('capa')
        
        # 2. Define o mascote como padrão caso o usuário não envie foto
        nome_capa = 'img/robo-pet-lindo.jpeg' 
        
        # 3. Se enviou uma capa válida, salva na pasta uploads
        if capa and allowed_file(capa.filename):
            import datetime
            nome_capa = f"capa_{int(datetime.datetime.now().timestamp())}_{secure_filename(capa.filename)}"
            capa.save(os.path.join(app.config['UPLOAD_FOLDER'], nome_capa))
        
        noticias = load_noticias_db()
        nova_noticia = {
            'id': int(datetime.datetime.now().timestamp()),
            'titulo': titulo,
            'conteudo': conteudo,
            'capa': nome_capa, # 4. Salva o nome da foto no JSON
            'autor': session['usuario_logado'],
            'data': datetime.datetime.now().strftime('%d/%m/%Y %H:%M')
        }
        noticias.insert(0, nova_noticia)
        save_noticias_db(noticias)
        
        flash('Notícia publicada com sucesso!')
        return redirect(url_for('noticias'))
        
    return render_template('criar_noticia.html')


@app.route('/upload_imagem', methods=['POST'])
def upload_imagem():
    if 'usuario_logado' not in session:
        return jsonify({'uploaded': 0, 'error': {'message': 'Faça login para enviar imagens.'}}), 401
    if 'upload' not in request.files:
        return jsonify({
            'uploaded': 0, 
            'error': {'message': 'Nenhum arquivo enviado.'}
        })
    
    file = request.files['upload']
    
    if file and allowed_file(file.filename):
        filename = secure_filename(file.filename)
        import datetime # Garantir que o datetime está importado
        nome_unico = f"{int(datetime.datetime.now().timestamp())}_{filename}"
        file_path = os.path.join(app.config['UPLOAD_FOLDER'], nome_unico)
        
        file.save(file_path)
        
        url = url_for('baixar_arquivo', filename=nome_unico)
        
        # O CKEditor exige EXATAMENTE este formato de resposta para funcionar
        return jsonify({
            'uploaded': 1,
            'fileName': nome_unico,
            'url': url
        })
    
    return jsonify({
        'uploaded': 0, 
        'error': {'message': 'Formato não permitido. Use JPG, PNG, etc.'}
    })

